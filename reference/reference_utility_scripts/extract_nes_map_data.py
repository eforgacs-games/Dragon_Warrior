"""
Extract the NES map data from the nmikstas disassembly into tests/nes_map_data.py.

Usage:
    python reference/reference_utility_scripts/extract_nes_map_data.py path/to/Bank00.asm > tests/nes_map_data.py

Bank00.asm is source_files/Bank00.asm from https://github.com/nmikstas/dragon-warrior-disassembly. The script reads:
- MapDatTbl: each map's data label, columns - 1, rows - 1 and boundary block (what's shown outside the map).
- Each map's data block (DLCstlGFDat, KolDat, RckMtnB2Dat, ...): one nibble per tile, two tiles per byte, the left tile
  in the upper nibble. Every row is written out as a string of hex digits, one digit per tile.
- WrldMapPtrTbl and Row000-Row119: the overworld, run-length encoded. Each byte is a block type in the upper nibble
  and (repeat count - 1) in the lower nibble. Every row's bytes are written out as a string of hex digits.

Lines that are commented out in the disassembly (the covered-area notes after RimuldarDat) aren't data and are skipped.
"""
import re
import sys

DATA_LINE = re.compile(r'^L([0-9A-F]{4}):\s+\.(byte|word)\s+([^;]*)')
LABEL_LINE = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*):')
MAP_COMMENT = re.compile(r'^;.*Map #\$([0-9A-F]{2})\.')


def parse(lines):
    """Labels -> address, and address -> byte for every .byte line."""
    labels: dict = {}
    memory: dict = {}
    words: dict = {}
    pending_labels: list = []
    for line in lines:
        data = DATA_LINE.match(line)
        if not data:
            label = LABEL_LINE.match(line)
            if label:
                pending_labels.append(label.group(1))
            continue
        address = int(data.group(1), 16)
        for name in pending_labels:
            labels[name] = address
        pending_labels = []
        values = [value.strip() for value in data.group(3).split(',') if value.strip()]
        if data.group(2) == 'byte':
            for offset, value in enumerate(values):
                if value.startswith('$'):
                    memory[address + offset] = int(value[1:], 16)
        else:
            words[address] = values
    return labels, memory, words


def map_table(lines):
    """MapDatTbl: map number -> (data label, columns, rows, boundary block)."""
    maps = {}
    start = lines.index('MapDatTbl:                      ;Data for game maps.\n')
    map_number = None
    pointer = None
    sizes: list = []
    for line in lines[start:]:
        comment = MAP_COMMENT.match(line)
        if comment:
            map_number = int(comment.group(1), 16)
            sizes = []
            continue
        data = DATA_LINE.match(line)
        if not data:
            if line.startswith(';---'):
                break
            continue
        value = data.group(3).split()[0]
        if data.group(2) == 'word':
            pointer = value
        else:
            sizes.append(int(value[1:], 16))
            if len(sizes) == 3 and pointer != 'NULL':
                columns, rows, boundary = sizes
                maps[map_number] = (pointer, columns + 1, rows + 1, boundary)
    return maps


def main(path):
    with open(path) as asm:
        lines = asm.readlines()
    labels, memory, words = parse(lines)
    maps = map_table(lines)
    print('"""')
    print('The NES map data, generated by reference/reference_utility_scripts/extract_nes_map_data.py from Bank00.asm in')
    print('the nmikstas disassembly (https://github.com/nmikstas/dragon-warrior-disassembly). Don\'t edit it by hand.')
    print('')
    print('MAPS: NES map number -> (MapDatTbl data label, columns, rows, rows of tiles). Each tile is one hex digit, the')
    print('map\'s own block type (see tests/nes_maps.py).')
    print('BOUNDARY_BLOCKS: NES map number -> the block ID shown outside the map (MapDatTbl).')
    print('OVERWORLD_ROWS: Row000 to Row119 (WrldMapPtrTbl), as hex bytes: block type, then repeat count - 1.')
    print('"""')
    print('')
    print('MAPS = {')
    for map_number, (label, columns, rows, _boundary) in sorted(maps.items()):
        if label == 'WrldMapPtrTbl':
            continue
        address = labels[label]
        bytes_per_row = (columns + 1) // 2
        print(f'    0x{map_number:02X}: ({label!r}, {columns}, {rows}, (')
        for row in range(rows):
            row_bytes = [memory[address + row * bytes_per_row + i] for i in range(bytes_per_row)]
            print(f"        '{''.join(f'{b:02X}' for b in row_bytes)[:columns]}',")
        print('    )),')
    print('}')
    print('')
    print('BOUNDARY_BLOCKS = {')
    for map_number, (_label, _columns, _rows, boundary) in sorted(maps.items()):
        print(f'    0x{map_number:02X}: 0x{boundary:02X},')
    print('}')
    print('')
    row_labels = [value for address in sorted(words) if address >= labels['WrldMapPtrTbl']
                  for value in words[address] if value.startswith('Row')][:120]
    print('OVERWORLD_ROWS = (')
    for index, label in enumerate(row_labels):
        assert label == f'Row{index:03d}', label
        address = labels[label]
        row = []
        column = 0
        while column < 120:
            value = memory[address + len(row)]
            row.append(value)
            column += (value & 0x0F) + 1
        # Row011's last run goes 2 blocks past the edge; the NES never reads past column 119
        assert column >= 120, (label, column)
        print(f"    '{''.join(f'{b:02X}' for b in row)}',  # {label}")
    print(')')


if __name__ == '__main__':
    main(sys.argv[1])
